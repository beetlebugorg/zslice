//! The facts of a G-code file that its slicer writes in comments: the
//! name of the slicer, the filament length and weight, and the settings.
//!
//! The reader of G-code (gcode_read.zig) gives this module each comment
//! of the form "key = value" or "key: value", and each comment that names
//! the slicer. The module keeps the notes of the start of the file (before
//! the first bead) and of its end (after the last bead). The notes between
//! the beads (";WIDTH:", ";MESH:") are dropped: the module keeps a mark at
//! the first bead, and cuts the list back to it at each bead.
//!
//! Where each slicer puts its facts:
//!
//! - CuraEngine: a header (";FLAVOR:", ";TIME:", ";Filament used: 1.2m",
//!   ";Layer height: 0.2") and ";Generated with Cura_SteamEngine 5.7".
//! - zslice: ";Generated by zslice" at the start, and ";Filament used:",
//!   ";Filament weight:", and the settings (";  project.layer_height =
//!   0.2") at the end.
//! - PrusaSlicer and OrcaSlicer: "; generated by PrusaSlicer 2.7 on ..."
//!   at the start, and "; filament used [mm] = " and the config at the
//!   end.
//! - Bambu Studio: a header block and a config block at the start
//!   ("; total filament length [mm] : ", "; BambuStudio 01.10").
//!
//! The comment formats are in REFERENCES.md.
//!
//! SPDX-License-Identifier: AGPL-3.0-or-later

const std = @import("std");
const Allocator = std.mem.Allocator;

/// The most notes, and the most bytes of their text. A config block of
/// Bambu Studio has about 600 notes.
const max_notes = 4096;
const max_text = 512 * 1024;

/// One note: the key and the value, as offsets into `Meta.text`. Each
/// ends in a NUL byte there.
pub const Note = struct {
    key: u32,
    value: u32,
};

pub const Meta = struct {
    /// The keys and the values, each with a NUL byte at the end.
    text: std.ArrayList(u8) = .empty,
    notes: std.ArrayList(Note) = .empty,
    /// The slicer and its version, with a NUL byte at the end.
    slicer_buf: [64]u8 = @splat(0),
    slicer_len: usize = 0,
    /// The mark at the first bead: the notes before it are the start of
    /// the file.
    in_body: bool = false,
    mark_notes: usize = 0,
    mark_text: usize = 0,

    pub fn deinit(m: *Meta, gpa: Allocator) void {
        m.text.deinit(gpa);
        m.notes.deinit(gpa);
        m.* = undefined;
    }

    /// The slicer, or "".
    pub fn slicer(m: *const Meta) [:0]const u8 {
        return m.slicer_buf[0..m.slicer_len :0];
    }

    /// A comment that names the slicer: "Generated with Cura_SteamEngine
    /// 5.7.1", "generated by PrusaSlicer 2.7.1 on ...", or "BambuStudio
    /// 01.10". The first one counts.
    pub fn slicerLine(m: *Meta, c: []const u8) void {
        if (m.slicer_len > 0) return;
        var s = c;
        if (std.ascii.startsWithIgnoreCase(s, "generated ")) {
            s = s["generated ".len..];
            for ([_][]const u8{ "with ", "by " }) |w| {
                if (std.ascii.startsWithIgnoreCase(s, w)) s = s[w.len..];
            }
        }
        if (std.mem.indexOf(u8, s, " on ")) |on| s = s[0..on];
        s = std.mem.trim(u8, s, " \t");
        const n = @min(s.len, m.slicer_buf.len - 1);
        @memcpy(m.slicer_buf[0..n], s[0..n]);
        m.slicer_buf[n] = 0;
        m.slicer_len = n;
    }

    /// A comment "key = value" or "key: value". A value of only '=' is
    /// the end of a line of a thumbnail (base64): the module skips it.
    pub fn note(m: *Meta, gpa: Allocator, k_text: []const u8, v_text: []const u8) Allocator.Error!void {
        if (k_text.len == 0) return;
        if (std.mem.trim(u8, v_text, "=").len == 0 and v_text.len > 0) return;
        if (m.notes.items.len >= max_notes or m.text.items.len + k_text.len + v_text.len + 2 > max_text) return;
        const k: u32 = @intCast(m.text.items.len);
        try m.text.ensureUnusedCapacity(gpa, k_text.len + v_text.len + 2);
        try m.notes.ensureUnusedCapacity(gpa, 1);
        m.text.appendSliceAssumeCapacity(k_text);
        m.text.appendAssumeCapacity(0);
        const v: u32 = @intCast(m.text.items.len);
        m.text.appendSliceAssumeCapacity(v_text);
        m.text.appendAssumeCapacity(0);
        m.notes.appendAssumeCapacity(.{ .key = k, .value = v });
    }

    /// A bead: the notes after the last bead go away, so only the notes
    /// of the start and of the end stay.
    pub fn bead(m: *Meta) void {
        if (!m.in_body) {
            m.in_body = true;
            m.mark_notes = m.notes.items.len;
            m.mark_text = m.text.items.len;
            return;
        }
        if (m.notes.items.len > m.mark_notes) {
            m.notes.items.len = m.mark_notes;
            m.text.items.len = m.mark_text;
        }
    }

    pub fn count(m: *const Meta) usize {
        return m.notes.items.len;
    }

    pub fn key(m: *const Meta, i: usize) [:0]const u8 {
        return m.at(m.notes.items[i].key);
    }

    pub fn value(m: *const Meta, i: usize) [:0]const u8 {
        return m.at(m.notes.items[i].value);
    }

    fn at(m: *const Meta, start: u32) [:0]const u8 {
        const t = m.text.items;
        const end = std.mem.indexOfScalarPos(u8, t, start, 0).?;
        return t[start..end :0];
    }

    /// The filament length (m) of the slicer, or null.
    pub fn meters(m: *const Meta) ?f64 {
        return m.find(&.{
            .{ "filament used", 1 },
            .{ "filament used [m]", 1 },
            .{ "filament used [mm]", 0.001 },
            .{ "total filament length [mm]", 0.001 },
        });
    }

    /// The filament weight (g) of the slicer, or null. A weight of 0 (a
    /// slicer with no density) counts as none.
    pub fn grams(m: *const Meta) ?f64 {
        const g = m.find(&.{
            .{ "filament weight", 1 },
            .{ "total filament used [g]", 1 },
            .{ "filament used [g]", 1 },
            .{ "total filament weight [g]", 1 },
        }) orelse return null;
        return if (g > 0) g else null;
    }

    /// The sum of the numbers of the first note with one of the keys (in
    /// the order of the list), times the scale of that key.
    fn find(m: *const Meta, keys: []const struct { []const u8, f64 }) ?f64 {
        for (keys) |k| {
            for (0..m.count()) |i| {
                if (!std.ascii.eqlIgnoreCase(m.key(i), k[0])) continue;
                if (sum(m.value(i))) |s| return s * k[1];
            }
        }
        return null;
    }
};

/// The sum of the numbers in a text: "1.2m, 0.5m" or "1200,500". Null if
/// it has no number.
fn sum(text: []const u8) ?f64 {
    var total: f64 = 0;
    var any = false;
    var it = std.mem.tokenizeAny(u8, text, ",; \t");
    while (it.next()) |tok| {
        var end: usize = 0;
        while (end < tok.len and (std.ascii.isDigit(tok[end]) or tok[end] == '.' or tok[end] == '-' or tok[end] == 'e' or tok[end] == 'E')) end += 1;
        // "1.2m": the unit stays out of the number.
        while (end > 0 and (tok[end - 1] == 'e' or tok[end - 1] == 'E')) end -= 1;
        const v = std.fmt.parseFloat(f64, tok[0..end]) catch continue;
        if (!std.math.isFinite(v)) continue;
        total += v;
        any = true;
    }
    return if (any) total else null;
}

const testing = std.testing;

test "gcode_meta: notes of the start and the end only" {
    var m: Meta = .{};
    defer m.deinit(testing.allocator);
    m.slicerLine("Generated with Cura_SteamEngine 5.13.0");
    m.slicerLine("generated by zslice");
    try testing.expectEqualStrings("Cura_SteamEngine 5.13.0", m.slicer());
    try m.note(testing.allocator, "Filament used", "3.38073m");
    try m.note(testing.allocator, "Layer height", "0.3");
    m.bead();
    try m.note(testing.allocator, "WIDTH", "0.45");
    m.bead();
    try m.note(testing.allocator, "Filament weight", "12.5g");
    try m.note(testing.allocator, "AAAA", "==");
    try testing.expectEqual(@as(usize, 3), m.count());
    try testing.expectEqualStrings("Layer height", m.key(1));
    try testing.expectEqualStrings("0.3", m.value(1));
    try testing.expectApproxEqAbs(@as(f64, 3.38073), m.meters().?, 1e-9);
    try testing.expectApproxEqAbs(@as(f64, 12.5), m.grams().?, 1e-9);
}

test "gcode_meta: the names of the slicers and the units" {
    var m: Meta = .{};
    defer m.deinit(testing.allocator);
    m.slicerLine("generated by PrusaSlicer 2.7.1+linux-x64 on 2024-01-01 at 10:00:00 UTC");
    try testing.expectEqualStrings("PrusaSlicer 2.7.1+linux-x64", m.slicer());
    try m.note(testing.allocator, "filament used [mm]", "1200.5, 300");
    try m.note(testing.allocator, "filament used [g]", "0.00");
    try testing.expectApproxEqAbs(@as(f64, 1.5005), m.meters().?, 1e-9);
    try testing.expect(m.grams() == null);
}
