// The Node test of the embeddable G-code viewer (zslice-view.js). It needs
// no browser: it reads G-code with GcodeFile in pieces of odd sizes, checks
// the facts, and draws frames of the view of the core (view.js) with the
// file loaded.
//
//   zig build web-view
//   node web/view/test-view.mjs zig-out/web/view [file.gcode ...]
//
// With no file, the test reads a small CuraEngine file and a small zslice
// file of its own.
//
// SPDX-License-Identifier: AGPL-3.0-or-later

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const dir = resolve(process.argv[2] ?? "zig-out/web/view");
const files = process.argv.slice(3);
const mod = await import(pathToFileURL(`${dir}/zslice-view.js`).href);
const { View3D } = await import(pathToFileURL(`${dir}/view.js`).href);
const { Wasm } = await import(pathToFileURL(`${dir}/wasm.js`).href);

const module = await WebAssembly.compile(await readFile(`${dir}/zslice.wasm`));
const wasm = await Wasm.create(module);

let failed = 0;
function expect(ok, what) {
  if (!ok) {
    failed++;
    console.log(`FAIL ${what}`);
  }
}

const cura = `;FLAVOR:Marlin
;TIME:1234
;Filament used: 0.05m
;Layer height: 0.2
;MINX:10
;Generated with Cura_SteamEngine 5.13.0
M82 ;absolute extrusion mode
G92 E0
G1 Z0.3 F600
G1 X0 Y5 E3 F1000
G92 E0
;LAYER_COUNT:3
;LAYER:0
G0 F3000 X10 Y10 Z0.3
;TYPE:WALL-OUTER
G1 F1200 X20 Y10 E0.4991
G1 X20 Y20 E0.9982
;TYPE:FILL
G1 X10 Y20 E1.4973
;MESH:part.stl
;LAYER:1
G0 X10 Y10 Z0.5
;TYPE:SKIN
G1 F1500 X20 Y10 E1.83
;LAYER:2
G0 X10 Y10 Z0.7
;TYPE:WALL-OUTER
G1 X20 Y10 E2.16
M104 S0
;End of Gcode
`;

const zslice = `;FLAVOR:Marlin
;Generated by zslice
;MACHINE:Generic
;LAYER_COUNT:2
M83
;LAYER:0
G1 Z0.2 F600
G1 X10 Y10 F3000
;TYPE:WALL-OUTER
G1 X20 Y10 E0.4 F1200
G1 X20 Y20 E0.4
;LAYER:1
G1 Z0.4
;TYPE:SKIN
G1 X10 Y20 E0.4
M104 S0
;Filament used: 0.002m
;Filament weight: 0.01g
;Estimated time: 42s
;zslice settings (the ones that differ from the defaults):
;  project.layer_height = 0.2
;  machine.nozzle_diameter = 0.4
`;

// Reads bytes in pieces of 7 bytes from a stream, to cut lines.
function stream(bytes, size) {
  let at = 0;
  return new ReadableStream({
    pull(c) {
      if (at >= bytes.length) return c.close();
      c.enqueue(bytes.subarray(at, at + size));
      at += size;
    },
  });
}

async function read(source) {
  const f = new mod.GcodeFile(wasm);
  await f.read(source);
  return f;
}

const enc = new TextEncoder();

{
  const f = await read(stream(enc.encode(cura), 7));
  const i = f.info();
  expect(i.layers === 3, `cura layers ${i.layers}`);
  expect(i.slicer === "Cura_SteamEngine 5.13.0", `cura slicer ${i.slicer}`);
  expect(Math.abs(i.meters - 0.05) < 1e-9, `cura meters ${i.meters}`);
  expect(i.gramsEstimated && i.grams > 0, `cura grams ${i.grams}`);
  expect(i.seconds > 0, `cura seconds ${i.seconds}`);
  expect(i.settings["Layer height"] === "0.2" && i.settings.FLAVOR === "Marlin", `cura settings ${JSON.stringify(i.settings)}`);
  expect(!("MESH" in i.settings), "cura MESH is in the body");
  expect(i.layerHeights.length === 3 && Math.abs(i.layerHeights[2] - 0.2) < 1e-6, `cura heights ${i.layerHeights}`);
  expect(Math.abs(f.layer(1).z - 0.5) < 1e-6, "cura layer 1 z");
  f.free();
}
{
  const f = await read(enc.encode(zslice));
  const i = f.info();
  expect(i.layers === 2, `zslice layers ${i.layers}`);
  expect(i.slicer === "zslice", `zslice slicer ${i.slicer}`);
  expect(!i.gramsEstimated && Math.abs(i.grams - 0.01) < 1e-9, `zslice grams ${i.grams}`);
  expect(Math.abs(i.seconds - 42) < 1e-6, `zslice seconds ${i.seconds}`);
  expect(!Object.keys(i.settings).some((k) => k.startsWith("zslice settings")), "zslice: the title of the settings is a note");
  expect(i.settings["project.layer_height"] === "0.2" && i.settings["machine.nozzle_diameter"] === "0.4", `zslice settings ${JSON.stringify(i.settings)}`);
  f.free();
}

// The view of the core shows a file: frames with beads, and fewer beads
// for a lower layer.
async function viewTest(name, bytes) {
  const t0 = performance.now();
  const f = await read(new Blob([bytes]));
  const t1 = performance.now();
  const i = f.info();
  const v = new View3D(wasm, 640, 480);
  wasm.x.zs_view_set_reduced(v.v, 1);
  expect(wasm.x.zs_view_load_gcode(v.v, f.g, 0, 0) === 0, `${name}: load`);
  wasm.x.zs_view_gcode_colors(v.v, 1, 0);
  wasm.x.zs_view_frame_part(v.v, 0.8);
  const beads = (fr) => {
    let n = 0;
    for (let k = 0; k < fr.drawsCount; k++) n += fr.draws[3 * k + 1];
    return n;
  };
  const all = beads(v.frame());
  wasm.x.zs_view_set_layer(v.v, Math.floor((i.layers - 1) / 2));
  const half = beads(v.frame());
  expect(all > 0 && half > 0 && half < all, `${name}: beads ${all} and ${half}`);
  console.log(`${name}: ${(i.size / 1e6).toFixed(1)} MB, ${i.layers} layers, ${i.beads} beads, read ${Math.round(t1 - t0)} ms, slicer "${i.slicer}", ${i.meters.toFixed(2)} m, ${i.grams.toFixed(1)} g${i.gramsEstimated ? " (estimate)" : ""}, ${Math.round(i.seconds)} s, ${Object.keys(i.settings).length} notes; frame beads ${all}, at half ${half}`);
  wasm.x.zs_view_free(v.v);
  f.free();
}

await viewTest("cura sample", enc.encode(cura));
await viewTest("zslice sample", enc.encode(zslice));
for (const path of files) await viewTest(path, await readFile(path));

if (failed) {
  console.log(`${failed} checks failed`);
  process.exit(1);
}
console.log("ok");
